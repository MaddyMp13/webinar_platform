test('client sampling excludes pause, buffering, and seek jumps',async()=>{
 const dom=new JSDOM('<video></video><p id="tracking-note"></p>',{url:'http://localhost/Task/webinar.html',runScripts:'outside-only'});
 const win=dom.window,video=win.document.querySelector('video');
 let milliseconds=0,sampler,heartbeat;
 Object.defineProperty(win.performance,'now',{value:()=>milliseconds});
 Object.defineProperty(video,'duration',{get:()=>60});
 win.crypto.randomUUID=randomUUID;
 win.setInterval=(fn,ms)=>{if(ms===1000)sampler=fn;else heartbeat=fn;return ms;};win.clearInterval=()=>{};
 const sent=[];
 win.WebinarAPI={request:async(resource,parameters,method,data)=>{if(resource==='playback_events')sent.push(...data.events);return {};}};
 vm.runInContext(fs.readFileSync(path.join(__dirname,'..','playback.js'),'utf8'),dom.getInternalVMContext());
 vm.runInContext('WebinarPlayback.attach(document.querySelector("video"),{id:1},{activityConsent:true})',dom.getInternalVMContext());
 video.dispatchEvent(new win.Event('playing'));await new Promise(resolve=>setImmediate(resolve));
 milliseconds=1000;video.currentTime=1;sampler();
 milliseconds=1500;video.currentTime=1.5;video.dispatchEvent(new win.Event('pause'));await new Promise(resolve=>setImmediate(resolve));
 milliseconds=100000;sampler();
 video.dispatchEvent(new win.Event('seeking'));video.currentTime=30;video.dispatchEvent(new win.Event('seeked'));await new Promise(resolve=>setImmediate(resolve));
 video.dispatchEvent(new win.Event('playing'));await new Promise(resolve=>setImmediate(resolve));
 milliseconds=101000;video.currentTime=31;sampler();heartbeat();await new Promise(resolve=>setImmediate(resolve));
 assert.equal(sent.reduce((sum,event)=>sum+event.watchedDeltaSeconds,0),2.5);
 assert.ok(sent.some(event=>event.type==='seeked' && event.previousPositionSeconds===1.5 && event.newPositionSeconds===30));
 vm.runInContext('WebinarPlayback.stop()',dom.getInternalVMContext());await new Promise(resolve=>setImmediate(resolve));dom.window.close();
});
